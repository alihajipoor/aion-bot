import type { giveaways } from '@aion/db';

type Row = typeof giveaways.$inferSelect;

/** Persian digits, because a Persian announcement with 30 in it reads half-translated. */
const fa = (n: number | string) => String(n).replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[Number(d)] ?? d);

/**
 * The announcement, in Persian.
 *
 * Reposted every 24 hours, so it is written to be read cold by someone who has
 * never seen it — the rules are in it, not linked from it. The rules section is
 * the load-bearing part: every dispute later is settled by pointing at it.
 */
export function announcement(g: Row): string {
  const ends = `<t:${Math.floor(g.endsAt.getTime() / 1000)}:R>`;
  const [first = 10, second = 7, third = 5] = g.floors;

  return [
    '# 🎁 مسابقه‌ی دعوت آیون',
    '',
    'هر چقدر آدم بیشتری به سرور بیاری، جایزه‌ی بزرگ‌تری می‌بری.',
    `مسابقه ${fa(3)} هفته‌ست و ${ends} تموم می‌شه.`,
    '',
    '## 🏆 جایزه‌ها',
    '',
    '**نفر اول** — خودت یکی رو انتخاب می‌کنی:',
    '> • باندل *World of Warcraft — Classic Forever* نسخه‌ی **Epic**',
    `> • گیفت کارت **${fa(60)} دلاری** استیم`,
    '> • **یک سال** دیسکورد نیترو',
    `> • **${fa(60)} دلار** تتر`,
    '',
    '**نفر دوم** — خودت یکی رو انتخاب می‌کنی:',
    '> • باندل *World of Warcraft — Classic Forever* نسخه‌ی **Heroic**',
    '> • **سه ماه** دیسکورد نیترو',
    `> • گیفت کارت **${fa(30)} دلاری** استیم`,
    `> • **${fa(30)} دلار** تتر`,
    '',
    '**نفر سوم**',
    `> • **یک ماه** دیسکورد نیترو **به‌علاوه‌ی** گیفت کارت ${fa(15)} دلاری استیم یا ${fa(15)} دلار تتر`,
    '',
    'هر سه نفر اول یه **رول دائمی** مخصوص خودشون می‌گیرن که برای همیشه روی پروفایلشون می‌مونه.',
    `هر کسی هم ${fa(3)} تا دعوت معتبر داشته باشه، رول **ʀᴇᴄʀᴜɪᴛᴇʀ** رو می‌گیره.`,
    '',
    '## ✅ چه دعوتی حساب می‌شه؟',
    '',
    'کسی که با لینک تو بیاد و این دو تا شرط رو داشته باشه:',
    `> • اکانت دیسکوردش حداقل **${fa(g.minAccountAgeDays)} روز** ساخته شده باشه`,
    '> • **وریفای** رو کامل کنه',
    '',
    '**لازم نیست چت کنه یا تو ویس بیاد.** همین که بیاد و وریفای کنه کافیه.',
    '**اگه بعداً از سرور بره، امتیازش مال تو می‌مونه.**',
    'هر نفر فقط **یک بار** حساب می‌شه — رفتن و دوباره اومدن چیزی اضافه نمی‌کنه،',
    'و کسی که از قبل عضو سرور بوده به عنوان دعوت جدید حساب نمی‌شه.',
    '',
    '⚠️ **اکانت فیک = حذف کامل از مسابقه**، نه فقط اون یه دعوت.',
    '',
    '## 📌 حداقل تعداد',
    '',
    `برای اینکه جایزه به کسی برسه، باید حداقل این تعداد دعوت معتبر داشته باشه:`,
    `> 🥇 نفر اول: **${fa(first)}** نفر`,
    `> 🥈 نفر دوم: **${fa(second)}** نفر`,
    `> 🥉 نفر سوم: **${fa(third)}** نفر`,
    '',
    '## 📊 دستورها',
    '',
    '`/giveaway board` — جدول مسابقه',
    '`/giveaway man` — دعوت‌های خودت، و دلیل اینکه کدوم حساب نشده و چرا',
    '',
    '## 🔗 چطور شروع کنم؟',
    '',
    'دکمه‌ی **لینک دعوت من** رو بزن — یه لینک مخصوص خودت می‌گیری که همیشه ثابت می‌مونه.',
    'هر کی با اون لینک بیاد، **دقیقاً** به اسم تو ثبت می‌شه. همینو برای دوستات بفرست.',
    '',
    '-# این صفحه هر ۲۴ ساعت دوباره فرستاده می‌شه.',
  ].join('\n');
}
